def main() -> int:
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "gen_batch09.py")
    with io.open(path, encoding="utf-8") as f:
        text = f.read()
    missing = []
    for old, new in FIXES:
        if f'"{old}"' not in text:
            missing.append(old)
            continue
        text = text.replace(f'"{old}"', f'"{new}"')
    with io.open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"applied {len(FIXES) - len(missing)} fixes")
    if missing:
        print("NOT FOUND:")
        for m in missing:
            print(" ", m)
    return 0


