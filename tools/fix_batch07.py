def main():
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "gen_batch07.py")
    with io.open(path, encoding="utf-8") as f:
        content = f.read()
    missing = []
    for old, new in FIXES:
        token = '"%s"' % old
        if content.count(token) == 0:
            missing.append(old)
            continue
        content = content.replace(token, '"%s"' % new)
    with io.open(path, "w", encoding="utf-8") as f:
        f.write(content)
    print("applied", len(FIXES) - len(missing), "fixes; missing:", missing)
    if missing:
        sys.exit(1)


if __name__ == "__main__":
    main()
