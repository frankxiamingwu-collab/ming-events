def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(os.path.dirname(here), "data", "raw", "batch_06.jsonl")
    seen = set()
    lines = []
    problems = []
    for d, p, n, c, s in EVENTS:
        if not (d[:4] in ("1642", "1643") and (len(d) == 4 or d[4] == "-")):
            problems.append(("date", d, s))
        if c not in CATS:
            problems.append(("cat", d, s))
        if not (15 <= len(s) <= 45):
            problems.append(("len:%d" % len(s), d, s))
        if '"' in s:
            problems.append(("quote", d, s))
        key = (d, p, s)
        if key in seen:
            problems.append(("dup", d, s))
        seen.add(key)
        lines.append(json.dumps({"d": d, "p": p, "n": n, "c": c, "s": s}, ensure_ascii=False))
    if problems:
        for pr in problems[:80]:
            print("PROBLEM", pr)
        print("total problems:", len(problems))
        raise SystemExit(1)
    lines.sort(key=lambda l: json.loads(l)["d"])
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("events:", len(lines), "->", out)




